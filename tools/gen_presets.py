#!/usr/bin/env python3
"""Generate Source/Presets.h (and web/presets.js) from presets.json."""
import json, re, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
dsp = open(os.path.join(root, 'Source/AnjiDSP.h')).read()
amps = re.findall(r'^\s*\{ "([^"]+)",\s+"', dsp.split('kAmps[]')[1].split('kNumAmps')[0], re.M)
cabs = re.findall(r'^\s*\{ "([^"]+)",', dsp.split('kCabs[]')[1].split('kNumCabs')[0], re.M)
modes = re.findall(r'"([^"]+)"', dsp.split('kDriveModes[] =')[1].split(';')[0])
presets = json.load(open(os.path.join(root, 'presets.json')))
enum = {'amp': amps, 'cab': cabs, 'od_mode': modes}
meta = {'name', 'category', 'notes'}
out = []
for p in presets:
    vals = {}
    for k, v in p.items():
        if k in meta: continue
        if k in enum:
            if v not in enum[k]: sys.exit(f'{p["name"]}: unknown {k} {v!r}')
            v = enum[k].index(v)
        vals[k] = float(v)
    out.append((p, vals))

def cstr(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
h = ['// GENERATED by tools/gen_presets.py from presets.json — do not edit', '#pragma once',
     '#include "ParamTable.h"', '#include <vector>', '#include <utility>', '', 'namespace anji', '{',
     'struct PresetDef { const char* name; const char* category; const char* notes; std::vector<std::pair<const char*, float>> values; };',
     '', 'inline const std::vector<PresetDef>& factoryPresets()', '{', '    static const std::vector<PresetDef> v = {']
for p, vals in out:
    kv = ', '.join('{ %s, %.4gf }' % (cstr(k), v) if v != int(v) else '{ %s, %d.0f }' % (cstr(k), int(v)) for k, v in vals.items())
    h.append('        { %s, %s, %s, { %s } },' % (cstr(p['name']), cstr(p['category']), cstr(p.get('notes', '')), kv))
h += ['    };', '    return v;', '}', '',
      'inline Params presetParams (const PresetDef& d)', '{',
      '    Params p = defaultParams();', '    for (auto& kv : d.values) if (auto* i = findParam (kv.first)) i->set (p, kv.second);',
      '    return p;', '}', '} // namespace anji', '']
open(os.path.join(root, 'Source/Presets.h'), 'w').write('\n'.join(h))
os.makedirs(os.path.join(root, 'web'), exist_ok=True)
js = {'amps': amps, 'cabs': cabs, 'driveModes': modes,
      'presets': [{'name': p['name'], 'category': p['category'], 'notes': p.get('notes', ''), 'values': vals} for p, vals in out]}
open(os.path.join(root, 'web/presets.js'), 'w').write('// GENERATED from presets.json\nconst ANJI_DATA = ' + json.dumps(js) + ';\n')
print(f'{len(out)} presets, {len(amps)} amps, {len(cabs)} cabs')

# ---- export full model tables for the web engine
def nums(tok): return [float(x.rstrip('f')) for x in tok]
ampdefs = []
for line in dsp.split('kAmps[]')[1].split('kNumAmps')[0].split('\n'):
    m = re.match(r'\s*\{ "([^"]+)",\s*"([^"]+)",(.*)\},\s*$', line)
    if not m: continue
    rest = m.group(3)
    groups = re.findall(r'\{([^}]*)\}', rest)
    flat = re.sub(r'\{[^}]*\}', 'G', rest)
    toks = [t.strip() for t in flat.split(',') if t.strip()]
    # toks: inHpf, bright, stages, G,G,G,G, gmin,gmax,bassF,bR,midF,mQ,mBase,mR,trebF,tR,pDrv,sag,pres,res,ss,trim
    g = [nums([x.strip() for x in grp.split(',')]) for grp in groups]
    t = [x for x in toks if x != 'G']
    v = lambda i: float(t[i].rstrip('f'))
    ampdefs.append(dict(name=m.group(1), blurb=m.group(2), inHpf=v(0), brightDb=v(1), stages=int(v(2)),
        stGain=g[0], stBias=g[1], stLpf=g[2], stHpf=g[3], gainMinDb=v(3), gainMaxDb=v(4), bassF=v(5), bassRange=v(6),
        midF=v(7), midQ=v(8), midBase=v(9), midRange=v(10), trebF=v(11), trebRange=v(12), powerDrive=v(13), sag=v(14),
        presF=v(15), resF=v(16), solidState=t[17] == 'true', trimDb=v(18)))
cabdefs = []
for line in dsp.split('kCabs[]')[1].split('kNumCabs')[0].split('\n'):
    m = re.match(r'\s*\{ "([^"]+)",(.*)\},\s*$', line)
    if not m: continue
    t = nums([x.strip() for x in m.group(2).split(',') if x.strip()])
    cabdefs.append(dict(zip(['name','hpf','resF','resDb','p1F','p1Db','p1Q','p2F','p2Db','p2Q','lpf'], [m.group(1)] + t)))
params = []
pt = open(os.path.join(root, 'Source/ParamTable.h')).read()
for m in re.finditer(r'P([FBC]) \("(\w+)",\s*"([^"]+)",\s*([^)]*)\)', pt):
    kind, pid, name, args = m.groups(); a = [x.strip() for x in args.split(',')]
    if kind == 'F': params.append(dict(id=pid, name=name, type='float', min=float(a[0].rstrip('f')), max=float(a[1].rstrip('f')), def_=float(a[2].rstrip('f')), unit=a[3].strip('"')))
    elif kind == 'B': params.append(dict(id=pid, name=name, type='bool', min=0, max=1, def_=float(a[0])))
    else: params.append(dict(id=pid, name=name, type='choice', min=0, max=None, def_=float(a[1])))
for p in params: p['def'] = p.pop('def_')
assert len(ampdefs) == len(amps) and len(cabdefs) == len(cabs), (len(ampdefs), len(cabdefs))
open(os.path.join(root, 'web/models.js'), 'w').write('// GENERATED from Source/AnjiDSP.h + ParamTable.h\nconst ANJI_AMPS = ' + json.dumps(ampdefs) +
    ';\nconst ANJI_CABS = ' + json.dumps(cabdefs) + ';\nconst ANJI_PARAMS = ' + json.dumps(params) + ';\n')
print('models.js:', len(ampdefs), 'amps', len(cabdefs), 'cabs', len(params), 'params')
